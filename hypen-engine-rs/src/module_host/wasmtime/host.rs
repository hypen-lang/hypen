//! [`Host`]: the native module host, generic over the module ABI.
//!
//! Everything a host does — registration, capability gating, the instance
//! table, deadlines, storage flushing, cross-module context, error mapping —
//! is implemented here once. An [`Abi`] supplies only what the two
//! `bindgen!` worlds make different: which interfaces to link and how to
//! call each export.

use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::Arc;

use wasmtime::component::{Component, InstancePre, Linker};
use wasmtime::Store;

use super::core::{Deadline, ExecStrategy, HostCore};
use super::cross_module::Acl;
use super::error::{self, CallFailure, DeniedImport, Export, RegisterError};
use super::instances::{IdTag, InstanceTable};
use super::limits::ModuleLimits;
use super::linker::{self, Capability, LinkFn};
use super::storage::SharedKv;
use super::store::{HostClock, HostState};
use crate::module_host::kv::{KvBackend, ModuleName};
use crate::module_host::{
    HostAction, HostError, ModuleHost, ModuleInstanceId, ModuleManifest, ReducerOutput,
    SiblingState,
};

/// What an export that can fail at the module level returns: the outer
/// result is the sandbox's (trap, timeout), the inner one the module's own.
pub(crate) type Reply<T> = wasmtime::Result<Result<T, String>>;

/// One version of the `hypen:module` contract, as generated by `bindgen!`.
///
/// Implementations are adapters only: they name the generated items and
/// convert generated types to the engine's. No policy lives in an `Abi`.
pub(crate) trait Abi: 'static {
    /// The `hypen:*` package version of this world, e.g. `"0.1.0"`.
    const VERSION: &'static str;
    /// The world, for messages, e.g. `"hypen:module@0.1.0"`.
    const WORLD: &'static str;
    /// The capabilities this world can import, each with the function that
    /// links it. A capability is linked only if the manifest grants it.
    const CAPABILITIES: &'static [(Capability, LinkFn)];

    /// A type-checked, ready-to-instantiate component (`ModuleXPre`).
    type Pre: Send + Sync;
    /// The exports of one instance (`ModuleX`).
    type Bindings: Send;

    /// Resolve the world's exports; fails if the component lacks them.
    fn prepare(pre: InstancePre<HostState>) -> wasmtime::Result<Self::Pre>;

    /// Instantiate, running the component's start code.
    async fn instantiate(
        pre: &Self::Pre,
        store: &mut Store<HostState>,
    ) -> wasmtime::Result<Self::Bindings>;

    async fn init(
        bindings: &Self::Bindings,
        store: &mut Store<HostState>,
        config: Vec<u8>,
    ) -> Reply<Vec<u8>>;

    async fn dispatch(
        bindings: &Self::Bindings,
        store: &mut Store<HostState>,
        state: Vec<u8>,
        action: HostAction,
    ) -> Reply<ReducerOutput>;

    async fn on_activated(
        bindings: &Self::Bindings,
        store: &mut Store<HostState>,
        state: Vec<u8>,
    ) -> Reply<ReducerOutput>;

    async fn on_deactivated(
        bindings: &Self::Bindings,
        store: &mut Store<HostState>,
        state: Vec<u8>,
    ) -> Reply<ReducerOutput>;

    async fn on_destroyed(
        bindings: &Self::Bindings,
        store: &mut Store<HostState>,
        state: Vec<u8>,
    ) -> Reply<()>;

    async fn actions(
        bindings: &Self::Bindings,
        store: &mut Store<HostState>,
    ) -> wasmtime::Result<Vec<String>>;
}

/// Whether a registered component can be instantiated under its manifest.
enum Linkage<A: Abi> {
    Ready(A::Pre),
    /// The component imports capabilities the manifest does not grant.
    /// Registration still succeeds — the bytes are fine — and every
    /// `instantiate` is refused with the list.
    Denied(Vec<DeniedImport>),
}

/// A registered module type. Instances hold an `Arc` to the registration
/// they were created from, so re-registering a name (hot reload) does not
/// change code or grants under a running instance.
struct Registration<A: Abi> {
    name: ModuleName,
    linkage: Linkage<A>,
    /// Cross-module grants, from the manifest's `reads` / `dispatches`.
    acl: Arc<Acl>,
}

struct Instance<A: Abi> {
    store: Store<HostState>,
    bindings: A::Bindings,
    registration: Arc<Registration<A>>,
}

/// What hosts on one core have in common: the wasmtime engine + epoch ticker
/// + runtime, and the storage backend.
#[derive(Clone)]
pub(crate) struct Shared {
    core: Arc<HostCore>,
    kv: SharedKv,
}

impl Shared {
    pub(crate) fn new(strategy: ExecStrategy, backend: KvBackend) -> Result<Self, HostError> {
        Ok(Self {
            core: HostCore::new(strategy)?,
            kv: SharedKv::new(backend),
        })
    }

    /// Persist what the call that just ended wrote. A failed flush must not
    /// cost the caller the guest's result, so it is logged (with the path)
    /// rather than returned; the store stays dirty and the next call — or
    /// an explicit `flush_storage` — retries.
    fn flush_after_call(&self) {
        if let Err(e) = self.kv.flush() {
            eprintln!("hypen: {e}; changes are kept in memory and the next call retries");
        }
    }
}

/// Native host for `hypen:module` WASM components. Use it through the two
/// aliases, [`WasmtimeHost`](crate::module_host::WasmtimeHost) (v0.1) and
/// [`WasmtimeHostAsync`](crate::module_host::WasmtimeHostAsync) (v0.2), or
/// through [`DualHost`](crate::module_host::DualHost), which routes both.
///
/// The [`ModuleHost`] surface is synchronous: each method blocks on the
/// host's own runtime. Do not call it from inside another tokio runtime's
/// async context (tokio refuses nested `block_on` and panics); use
/// `spawn_blocking` there.
// `Abi` is deliberately crate-private: the ABI set is closed, and the only
// instantiations reachable from outside are the two exported aliases.
#[allow(private_bounds)]
pub struct Host<A: Abi> {
    // Field order is drop order: instances (stores, which may own WASI
    // resources tied to the runtime) go before `shared` can release the
    // runtime.
    instances: InstanceTable<Instance<A>>,
    modules: HashMap<ModuleName, Arc<Registration<A>>>,
    clock: HostClock,
    limits: ModuleLimits,
    shared: Shared,
}

#[allow(private_bounds)]
impl<A: Abi> Host<A> {
    /// Create a host with the default [`ModuleLimits`].
    pub fn new() -> Result<Self, HostError> {
        Self::with_limits(ModuleLimits::default())
    }

    /// Create a host with explicit resource limits. Every instance this host
    /// creates is bounded by `limits`.
    pub fn with_limits(limits: ModuleLimits) -> Result<Self, HostError> {
        Self::with_options(limits, ExecStrategy::default())
    }

    /// Create a host with explicit limits and execution strategy
    /// ([`ExecStrategy::Interpreter`] = Pulley, for JIT-forbidden platforms
    /// such as iOS).
    pub fn with_options(limits: ModuleLimits, strategy: ExecStrategy) -> Result<Self, HostError> {
        let shared = Shared::new(strategy, KvBackend::default())?;
        Ok(Self::on(shared, limits, IdTag::Plain))
    }

    /// Create a host on an existing core and storage backend, so `DualHost`
    /// runs both ABIs on one of each. `tag` marks the ids it issues.
    pub(crate) fn on(shared: Shared, limits: ModuleLimits, tag: IdTag) -> Self {
        Self {
            instances: InstanceTable::new(tag),
            modules: HashMap::new(),
            clock: HostClock::real(),
            limits,
            shared,
        }
    }

    /// Back `local`/`app` storage with a JSON snapshot file at `path`,
    /// loading anything a previous process persisted there (an unreadable or
    /// other-format file is an error; it is never overwritten). Changes are
    /// flushed at the end of each module call. Call before instantiating
    /// modules; existing in-memory contents are replaced. `cloud` stays
    /// in-memory (it simulates a sync service, not a disk).
    pub fn set_storage_path(&mut self, path: impl Into<PathBuf>) -> Result<(), HostError> {
        let backend = KvBackend::file_backed(path.into()).map_err(storage_error)?;
        self.shared.kv.replace(backend);
        Ok(())
    }

    /// Persist pending storage changes now. The host already flushes at the
    /// end of every module call, but a failure there is only logged (the
    /// call's result takes precedence); this is how an embedder observes it
    /// or retries. Ok when there is nothing to write or storage is
    /// in-memory.
    pub fn flush_storage(&mut self) -> Result<(), HostError> {
        self.shared.kv.flush().map_err(storage_error)
    }

    /// Why the instance behind `id` is dead — the trap or timeout that
    /// killed it, naming the module and the export — or `None` if it is
    /// live, was destroyed, or was never issued by this host. Calls on a
    /// dead instance return the bare [`HostError::DeadInstance`]; this is
    /// the detail behind it.
    pub fn death_reason(&self, id: ModuleInstanceId) -> Option<String> {
        self.instances.death_reason(id).map(ToString::to_string)
    }

    /// Forget a registration (used when a name moves to the other ABI).
    /// Existing instances keep running the code they were created from.
    pub(crate) fn unregister(&mut self, name: &str) {
        self.modules.remove(name);
    }

    pub(crate) fn set_clock(&mut self, clock: HostClock) {
        self.clock = clock;
    }

    fn deadline(&self) -> Deadline {
        Deadline::after(self.limits.max_call)
    }

    /// Compile and type-check a component for registration.
    fn prepare(
        &self,
        bytes: &[u8],
        manifest: &ModuleManifest,
    ) -> Result<Linkage<A>, RegisterError> {
        // Say what the bytes are before wasmtime says what they are not.
        match bytes.get(..8) {
            Some([0, b'a', b's', b'm', version @ ..]) => {
                // Layer 0 (`01 00 00 00`) is a core module, layer 1 a
                // component.
                if version == [1, 0, 0, 0] {
                    return Err(RegisterError::CoreModule);
                }
            }
            _ => return Err(RegisterError::NotWasm),
        }
        let engine = self.shared.core.engine();
        let component = Component::from_binary(engine, bytes)
            .map_err(|e| RegisterError::Invalid(format!("{e:#}")))?;

        let denied = linker::inspect::<A>(engine, &component, manifest)?;
        if !denied.is_empty() {
            return Ok(Linkage::Denied(denied));
        }
        let linker: Linker<HostState> = linker::build::<A>(engine, manifest)
            .map_err(|e| RegisterError::Host(format!("{e:#}")))?;
        let pre = linker
            .instantiate_pre(&component)
            .map_err(|e| RegisterError::Unlinkable {
                world: A::WORLD,
                why: format!("{e:#}"),
            })?;
        let pre = A::prepare(pre).map_err(|e| RegisterError::MissingExports {
            world: A::WORLD,
            why: format!("{e:#}"),
        })?;
        Ok(Linkage::Ready(pre))
    }

    /// Run one export of a live instance under the per-call deadline.
    ///
    /// Afterwards, storage the call wrote is flushed, and — if the call
    /// trapped or overran the deadline — the instance is killed: its store
    /// is dropped and later calls get [`HostError::DeadInstance`]. An
    /// export that returns `Err(string)` is a module-level error and leaves
    /// the instance alive.
    fn call<R>(
        &mut self,
        id: ModuleInstanceId,
        export: Export,
        run: impl AsyncFnOnce(&A::Bindings, &mut Store<HostState>) -> Reply<R>,
    ) -> Result<R, HostError> {
        let deadline = self.deadline();
        let Instance {
            store,
            bindings,
            registration,
        } = self.instances.live_mut(id)?;
        let module = registration.name.clone();

        let outcome = self
            .shared
            .core
            .run_guest(deadline, store, async |store| run(bindings, store).await);
        self.shared.flush_after_call();

        match outcome {
            Ok(Ok(value)) => Ok(value),
            Ok(Err(message)) => Err(error::module_error(&module, export, &message)),
            Err(fault) => {
                let failure = CallFailure {
                    module,
                    export,
                    fault,
                };
                let error = failure.to_host_error();
                self.instances.kill(id, failure);
                Err(error)
            }
        }
    }

    /// [`call`](Self::call) for the exports that may use
    /// `hypen:engine/state` (`dispatch`, `on-activated`): opens the
    /// cross-module window (ACL + sibling snapshots) for the duration of the
    /// call and moves the requests the guest queued into the output.
    fn call_with_siblings(
        &mut self,
        id: ModuleInstanceId,
        export: Export,
        siblings: &[SiblingState],
        run: impl AsyncFnOnce(&A::Bindings, &mut Store<HostState>) -> Reply<ReducerOutput>,
    ) -> Result<ReducerOutput, HostError> {
        let instance = self.instances.live_mut(id)?;
        let acl = Arc::clone(&instance.registration.acl);
        instance.store.data_mut().cross.begin(acl, siblings);

        let result = self.call(id, export, run);

        // If the call killed the instance its store (and context) is gone.
        // Otherwise close the window whether or not the reducer succeeded,
        // and keep the queued requests only on success.
        let Ok(instance) = self.instances.live_mut(id) else {
            return result;
        };
        let requests = instance.store.data_mut().cross.end();
        let mut output = result?;
        requests.attach_to(&mut output);
        Ok(output)
    }
}

fn storage_error(e: impl std::fmt::Display) -> HostError {
    HostError::Runtime(e.to_string())
}

#[allow(private_bounds)]
impl<A: Abi> ModuleHost for Host<A> {
    /// Register (or replace) a module type.
    ///
    /// Fails if the bytes are not a component of this host's world (the
    /// error says which: not wasm, a core module, another ABI version,
    /// unlinkable imports, missing exports). A component that merely
    /// imports capabilities its manifest does not grant registers fine and
    /// is refused at [`instantiate`](ModuleHost::instantiate).
    ///
    /// Re-registering a name affects **later** `instantiate` calls only:
    /// live instances keep the code and the manifest they were created
    /// with until they are destroyed. A failed re-registration leaves the
    /// previous one in place.
    fn register(
        &mut self,
        name: &str,
        component_bytes: &[u8],
        manifest: ModuleManifest,
    ) -> Result<(), HostError> {
        let linkage = self
            .prepare(component_bytes, &manifest)
            .map_err(|e| e.into_host_error(name))?;
        let name = ModuleName::new(name);
        let registration = Registration {
            name: name.clone(),
            linkage,
            acl: Arc::new(Acl::from_manifest(&manifest)),
        };
        self.modules.insert(name, Arc::new(registration));
        Ok(())
    }

    fn instantiate(&mut self, name: &str) -> Result<ModuleInstanceId, HostError> {
        let registration = self
            .modules
            .get(name)
            .map(Arc::clone)
            .ok_or_else(|| HostError::UnknownModule(name.to_string()))?;
        let pre = match &registration.linkage {
            Linkage::Ready(pre) => pre,
            Linkage::Denied(denied) => {
                return Err(error::capability_denied(&registration.name, denied));
            }
        };

        let state = HostState::new(
            registration.name.clone(),
            self.shared.kv.clone(),
            self.clock.clone(),
            &self.limits,
        );
        let mut store = Store::new(self.shared.core.engine(), state);
        store.limiter(|state| &mut state.limiter);

        // Component start runs guest code (heavy for JS engines), so it gets
        // the same deadline as an export call.
        let started = self
            .shared
            .core
            .run_guest(self.deadline(), &mut store, async |store| {
                A::instantiate(pre, store).await
            });
        // Persist anything the component's start wrote, even if it failed.
        self.shared.flush_after_call();

        let bindings = started.map_err(|fault| {
            let module = registration.name.clone();
            CallFailure {
                module,
                export: Export::Start,
                fault,
            }
            .to_host_error()
        })?;
        Ok(self.instances.insert(Instance {
            store,
            bindings,
            registration,
        }))
    }

    fn destroy(&mut self, id: ModuleInstanceId) -> Result<(), HostError> {
        self.instances.remove(id)
    }

    fn init(&mut self, id: ModuleInstanceId, config: &[u8]) -> Result<Vec<u8>, HostError> {
        let config = config.to_vec();
        self.call(id, Export::Init, async |b, store| {
            A::init(b, store, config).await
        })
    }

    fn dispatch(
        &mut self,
        id: ModuleInstanceId,
        state: &[u8],
        action: HostAction,
        siblings: &[SiblingState],
    ) -> Result<ReducerOutput, HostError> {
        let state = state.to_vec();
        self.call_with_siblings(id, Export::Dispatch, siblings, async |b, store| {
            A::dispatch(b, store, state, action).await
        })
    }

    fn on_activated(
        &mut self,
        id: ModuleInstanceId,
        state: &[u8],
        siblings: &[SiblingState],
    ) -> Result<ReducerOutput, HostError> {
        // Same cross-module window as `dispatch`, so a hook that reads /
        // dispatches / subscribes from `on_activated` is gated identically.
        let state = state.to_vec();
        self.call_with_siblings(id, Export::OnActivated, siblings, async |b, store| {
            A::on_activated(b, store, state).await
        })
    }

    fn on_deactivated(
        &mut self,
        id: ModuleInstanceId,
        state: &[u8],
    ) -> Result<ReducerOutput, HostError> {
        // No cross-module window: the module is leaving the screen and gets
        // no sibling snapshots, so `hypen:engine/state` calls are denied.
        let state = state.to_vec();
        self.call(id, Export::OnDeactivated, async |b, store| {
            A::on_deactivated(b, store, state).await
        })
    }

    fn on_destroyed(&mut self, id: ModuleInstanceId, state: &[u8]) -> Result<(), HostError> {
        let state = state.to_vec();
        self.call(id, Export::OnDestroyed, async |b, store| {
            A::on_destroyed(b, store, state).await
        })
    }

    fn actions(&mut self, id: ModuleInstanceId) -> Result<Vec<String>, HostError> {
        // `actions` cannot fail at the module level (no `result` in the WIT).
        self.call(id, Export::Actions, async |b, store| {
            A::actions(b, store).await.map(Ok)
        })
    }
}
