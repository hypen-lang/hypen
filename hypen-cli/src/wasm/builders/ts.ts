/**
 * TypeScript pipeline, per stateful module:
 *
 *   1. **Entry** — generate a small entry file that hands the user's module
 *      and the host's `hypen:engine/state` import to the shim
 *      (`shims/module-shim.ts`), which adapts the module definition to the
 *      `hypen:module` reducer ABI. The author never writes WIT.
 *   2. **Bundle** — esbuild bundles entry + shim + the user module + its
 *      imports (`@hypen-space/core`) into one ESM file, with Node built-ins
 *      stubbed so the bundle targets WASI, not Node.
 *   3. **Componentize** — `jco componentize` wraps the bundle (carrying the
 *      StarlingMonkey JS engine) into a Component implementing `hypen:module`.
 */

import { readdirSync, writeFileSync } from "fs";
import { dirname, isAbsolute, join, resolve } from "path";
import { BuildError } from "../../build-error.js";
import { bundledWitDir, tsShimPath } from "../assets.js";
import { assertComponent } from "../artifact.js";
import { assertNoForeignModule, componentSources } from "../discover.js";
import { wasmFileName } from "../manifest.js";
import { nodeStubPlugin } from "../node-stubs.js";
import { expectSuccess, runTool } from "../process.js";
import { JCO_PACKAGE, JCO_VERSION, findJco, requireTool, type JcoTool } from "../toolchain.js";
import { parseModuleName, type Discovery } from "../types.js";
import { ENGINE_STATE_IMPORT, TS_BUILD_WORLD, writeTsWit } from "../wit.js";
import type { ModuleBuilder } from "./builder.js";

/** What a TS module is built from. */
export interface TsSource {
  /** Absolute path of the module's `.ts` file (its default export is the definition). */
  modulePath: string;
  /** Action names the module handles, read from the loaded definition. */
  actions: string[];
}

interface TsPrepared {
  jco: JcoTool;
  esbuild: typeof import("esbuild");
  /** The bundled `hypen:module@0.1` WIT. */
  witDir: string;
  shimPath: string;
}

/**
 * The entry file esbuild bundles for one module. All logic lives in the shim;
 * this only supplies what differs per module: where the user's module is and
 * which WIT package version the host import is bound under.
 *
 * The `hypen:engine/state` specifier carries the WIT package version because
 * componentize-js binds world imports under their fully versioned name — an
 * unversioned specifier fails at component initialization ("Error loading
 * module").
 */
export function tsShimEntrySource(options: {
  /** Path of the user's module file. */
  modulePath: string;
  /** Path of the shim module (`tsShimPath()`). */
  shimPath: string;
  /** Versioned specifier of the engine-state import. Default: `ENGINE_STATE_IMPORT`. */
  engineStateImport?: string;
}): string {
  const { modulePath, shimPath, engineStateImport = ENGINE_STATE_IMPORT } = options;
  return [
    "// AUTO-GENERATED by `hypen build --target wasm`. Do not edit.",
    `import def from ${JSON.stringify(modulePath)};`,
    `import { read, subscribe } from ${JSON.stringify(engineStateImport)};`,
    `import { createModuleExports } from ${JSON.stringify(shimPath)};`,
    "",
    "const hypenModule = createModuleExports(def, { read, subscribe });",
    "",
    // Named exports, one per world export: componentize-js matches them by name.
    "export const init = hypenModule.init;",
    "export const dispatch = hypenModule.dispatch;",
    "export const onActivated = hypenModule.onActivated;",
    "export const onDeactivated = hypenModule.onDeactivated;",
    "export const onDestroyed = hypenModule.onDestroyed;",
    "export const actions = hypenModule.actions;",
    "",
  ].join("\n");
}

/** esbuild's rejection when a build has errors. */
function isBuildFailure(error: unknown): error is import("esbuild").BuildFailure {
  return (
    error instanceof Error &&
    "errors" in error &&
    Array.isArray(error.errors) &&
    "warnings" in error &&
    Array.isArray(error.warnings)
  );
}

export const tsBuilder: ModuleBuilder<TsSource, TsPrepared> = {
  language: "ts",
  label: "TypeScript (jco)",

  async discover(project) {
    // The same discovery the dev server / RemoteServer use, so the wasm build
    // sees exactly what `hypen dev` sees.
    const { discoverComponents, loadDiscoveredComponents } = await import("@hypen-space/server");
    const discovered = await discoverComponents(project.componentsDir);
    // Loading runs each module file (to read its definition), so a module
    // that throws at import time, or imports something unresolvable, fails
    // here — before any of them is compiled.
    const loaded = await loadDiscoveredComponents(discovered).catch((cause: unknown) => {
      throw new BuildError(
        `Could not load the project's modules: ${cause instanceof Error ? cause.message : String(cause)}`,
        {
          code: "MODULE_LOAD_FAILED",
          file: project.componentsDir,
          hint: "a module file failed while being imported: fix the error it reports (and install the project's dependencies if an import is unresolved)",
          cause,
        }
      );
    });
    const found: Discovery<TsSource> = { stateful: [], stateless: [] };
    for (const d of discovered) {
      const definition = loaded.get(d.name)?.module;
      if (d.hasModule && d.modulePath && definition) {
        found.stateful.push({
          kind: "stateful",
          name: parseModuleName(d.name),
          template: loaded.get(d.name)?.template ?? d.template ?? "",
          source: {
            modulePath: isAbsolute(d.modulePath)
              ? d.modulePath
              : resolve(project.projectDir, d.modulePath),
            actions: definition.actions ?? [],
          },
        });
      } else if (d.template) {
        // Only a component in its own directory can be checked for another
        // language's sources; a `Name.hypen` in the components root shares
        // that directory with every other component.
        const dir = d.hypenPath ? dirname(resolve(project.projectDir, d.hypenPath)) : undefined;
        if (dir !== undefined && dir !== project.componentsDir) {
          const sources = { ...componentSources(d.name, readdirSync(dir)), ts: false };
          assertNoForeignModule({ name: d.name, dir, sources }, "ts", project.prebuilt);
        }
        found.stateless.push({ kind: "stateless", name: parseModuleName(d.name), template: d.template });
      }
    }
    return found;
  },

  entryHint: (entry) =>
    `a wasm build needs the entry to have a module (${entry}.ts with app.defineState(...).build())`,

  describe: (module) => ({ built: `(${module.source.actions.length} action(s))` }),

  async prepare(ctx) {
    const jco = requireTool(findJco(ctx.project.projectDir));
    if (jco.version !== undefined && jco.version !== JCO_VERSION) {
      ctx.log(
        `using ${jco.origin === "project" ? "the project's" : "the CLI's"} ${JCO_PACKAGE} ${jco.version} ` +
          `(the CLI is tested with ${JCO_VERSION})`
      );
    }
    let esbuild: typeof import("esbuild");
    try {
      esbuild = await import("esbuild");
    } catch (cause) {
      throw new BuildError("The TypeScript wasm target needs esbuild, which could not be loaded.", {
        code: "TOOLCHAIN_MISSING",
        hint: "reinstall @hypen-space/cli (esbuild is one of its dependencies)",
        cause,
      });
    }
    return { jco, esbuild, witDir: bundledWitDir("module-0.1"), shimPath: tsShimPath() };
  },

  async build(ctx, prepared, module, capabilities) {
    const { projectDir } = ctx.project;
    const entryPath = join(ctx.workDir, `shim-${module.name}.mjs`);
    const bundlePath = join(ctx.workDir, `bundle-${module.name}.mjs`);
    const wasmPath = join(ctx.stageDir, wasmFileName(module.name));

    writeFileSync(
      entryPath,
      tsShimEntrySource({ modulePath: module.source.modulePath, shimPath: prepared.shimPath })
    );

    const { esbuild } = prepared;
    try {
      const result = await esbuild.build({
        entryPoints: [entryPath],
        bundle: true,
        outfile: bundlePath,
        format: "esm",
        platform: "neutral",
        target: "es2022",
        // "bun" first resolves workspace packages to their source entry.
        conditions: ["bun", "import", "default"],
        // `hypen:engine/state` is a WIT import satisfied by the host at
        // instantiation, not a resolvable module — keep it out of the bundle.
        external: [ENGINE_STATE_IMPORT],
        plugins: [nodeStubPlugin()],
        // Diagnostics are reported below, once: warnings as progress output,
        // errors on the BuildError.
        logLevel: "silent",
        absWorkingDir: projectDir,
      });
      const warnings = await esbuild.formatMessages(result.warnings, { kind: "warning", color: false });
      for (const warning of warnings) process.stderr.write(warning);
    } catch (cause) {
      const errors = isBuildFailure(cause) ? cause.errors : [];
      const formatted = await esbuild.formatMessages(errors.slice(0, 10), { kind: "error", color: false });
      throw new BuildError(
        `esbuild could not bundle ${module.name}` + (errors.length > 0 ? ` (${errors.length} error(s))` : ""),
        {
          code: "BUNDLE_FAILED",
          module: module.name,
          file: module.source.modulePath,
          detail:
            errors.length > 0
              ? formatted.flatMap((m) => m.trimEnd().split("\n"))
              : [cause instanceof Error ? cause.message : String(cause)],
          hint: "every import of the module must resolve from the project and be usable outside Node/Bun (run the package manager's install if a dependency is missing)",
          cause,
        }
      );
    }

    // Componentize against the module's narrowed world (`tsBuildWorld`).
    // `--disable http fetch-event` keeps every wasi:http import out of the
    // component: with only `http` disabled, StarlingMonkey's fetch-event
    // support still imports wasi:http/types, which the host doesn't link
    // without an `http` grant. Clocks/random stay (Date / Math.random).
    const witDir = join(ctx.workDir, `wit-${module.name}`);
    writeTsWit(prepared.witDir, witDir, capabilities.storage);
    const { jco } = prepared;
    const run = await runTool(
      jco.cmd,
      [
        ...jco.pre,
        "componentize",
        bundlePath,
        "--wit",
        witDir,
        "--world-name",
        TS_BUILD_WORLD,
        "-o",
        wasmPath,
        "--disable",
        "http",
        "fetch-event",
      ],
      { cwd: projectDir, output: "stream" }
    );
    expectSuccess(run, "jco componentize", {
      module: module.name,
      file: module.source.modulePath,
      hint:
        `the bundle is at ${bundlePath} (re-run with --keep-temp to inspect it); top-level code in the ` +
        `module runs at build time under componentize-js and must not throw`,
    });
    const reinstall = `install ${JCO_PACKAGE} in the project (bun add -d ${JCO_PACKAGE}@${JCO_VERSION}) and retry`;
    assertComponent(wasmPath, module.name, "jco componentize", {
      // A mis-resolved `jco` (a stub, another package's bin) can exit 0
      // without writing anything.
      noOutput: `${jco.cmd} may not be the real jco: ${reinstall}`,
      notComponent: reinstall,
    });
    return { name: module.name, wasmPath };
  },
};
