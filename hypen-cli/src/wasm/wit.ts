/**
 * Putting the right WIT in front of each toolchain: the narrowed per-module
 * world the TS pipeline componentizes against, and the `wit/` directory a
 * Rust crate's `wit_bindgen::generate!` reads.
 */

import {
  cpSync,
  existsSync,
  readFileSync,
  readdirSync,
  renameSync,
  rmSync,
  statSync,
  writeFileSync,
} from "fs";
import { join } from "path";
import { BuildError } from "../build-error.js";
import { bundledModuleWit } from "./assets.js";
import type { Abi, GrantableStorage } from "./types.js";

/**
 * Import specifier of the cross-module state capability the TS shim uses. The
 * version must match `package hypen:engine@…` in `wit/deps/hypen-engine/state.wit`
 * (asserted by tests/build-wasm.test.ts).
 */
export const ENGINE_STATE_IMPORT = "hypen:engine/state@0.1.0";

/** Name of the per-module world `tsBuildWorld` generates. */
export const TS_BUILD_WORLD = "hypen-cli-build";

const MODULE_WIT_FILE = "hypen-module.wit";

/**
 * The world a TS module is componentized against: `module` (all reducer
 * exports) plus the `hypen:engine/state` import, but with only the storage
 * imports the module is granted.
 *
 * componentize-js keeps *every* import of the target world in the component,
 * used or not, and the host links `hypen:storage/app` / `cloud` only for
 * modules granted them (an ungranted import fails instantiation). Building
 * against `module-x` verbatim would therefore make every TS module need
 * `"storage": ["app", "cloud"]`. `module`'s body is copied from the vendored
 * WIT (so exports stay in lockstep), minus the ungranted storage imports.
 */
export function tsBuildWorld(moduleWit: string, storage: readonly GrantableStorage[]): string {
  const broken = (what: string) =>
    new BuildError(`bundled WIT ${what}`, {
      code: "CLI_ASSET_MISSING",
      file: MODULE_WIT_FILE,
      hint: "the CLI install is incomplete: reinstall @hypen-space/cli",
    });
  const start = moduleWit.search(/^world module \{/m);
  if (start < 0) throw broken("has no `world module`");
  let depth = 0;
  let end = -1;
  for (let i = start; i < moduleWit.length; i++) {
    if (moduleWit[i] === "{") depth++;
    else if (moduleWit[i] === "}" && --depth === 0) {
      end = i;
      break;
    }
  }
  if (end < 0) throw broken("`world module` is unterminated");
  const granted = new Set<string>(storage);
  const body = moduleWit
    .slice(moduleWit.indexOf("{", start) + 1, end)
    .split("\n")
    .filter((line) => {
      const tier = line.match(/^\s*import\s+hypen:storage\/(app|cloud)@/)?.[1];
      return tier === undefined || granted.has(tier);
    })
    .join("\n");
  return (
    `\n// Generated by \`hypen build --target wasm\`: \`module\` with only this\n` +
    `// module's granted storage imports, plus hypen:engine/state.\n` +
    `world ${TS_BUILD_WORLD} {${body}    import ${ENGINE_STATE_IMPORT};\n}\n`
  );
}

/**
 * Copy the bundled WIT to `dest` with the module's `tsBuildWorld` appended,
 * for `jco componentize --world-name`.
 */
export function writeTsWit(witDir: string, dest: string, storage: readonly GrantableStorage[]): void {
  rmSync(dest, { recursive: true, force: true });
  cpSync(witDir, dest, { recursive: true });
  const file = join(dest, MODULE_WIT_FILE);
  const src = readFileSync(file, "utf8");
  writeFileSync(file, src + tsBuildWorld(src, storage));
}

/** Marker the CLI drops into a `wit/` it provisioned (vs. one the author vendored). */
export const PROVISIONED_MARKER = ".hypen-provisioned";

const PROVISIONED_NOTE =
  "Provisioned by `hypen build --target wasm`; refreshed whenever the CLI's WIT changes.\n" +
  "Delete this file to take ownership of wit/ (the CLI will then leave it alone).\n";

/** Relative paths of every file under `dir`, sorted (marker excluded). */
function listTree(dir: string, prefix = ""): string[] {
  const out: string[] = [];
  for (const name of readdirSync(dir).sort()) {
    if (!prefix && name === PROVISIONED_MARKER) continue;
    const abs = join(dir, name);
    const rel = prefix ? `${prefix}/${name}` : name;
    if (statSync(abs).isDirectory()) out.push(...listTree(abs, rel));
    else out.push(rel);
  }
  return out;
}

/** True when the two directory trees hold the same files with the same bytes. */
export function sameTree(a: string, b: string): boolean {
  if (!existsSync(a) || !existsSync(b)) return false;
  const fa = listTree(a);
  const fb = listTree(b);
  if (fa.length !== fb.length || fa.some((f, i) => f !== fb[i])) return false;
  return fa.every((f) => readFileSync(join(a, f)).equals(readFileSync(join(b, f))));
}

/** The bundled `hypen:module` WIT trees, by ABI. */
export type BundledWit = Record<Abi, string>;

/** What `provisionRustWit` did to a crate's `wit/`. */
export type WitProvisioning =
  /** No `wit/` existed; the CLI's was copied in. */
  | "provisioned"
  /** A CLI-owned `wit/` differed from the WIT for the crate's ABI and was replaced. */
  | "refreshed"
  /** A CLI-owned `wit/` already matched. */
  | "unchanged"
  /** The author owns `wit/`; it was left alone. */
  | "vendored";

/**
 * Replace `dest` with a copy of `src` plus the provisioning marker. Staged in
 * a sibling directory and renamed into place: an interrupted copy must not
 * leave a half-written, unmarked `wit/` that later builds would mistake for
 * an author-vendored one and never refresh.
 */
function installWit(src: string, dest: string): void {
  const staging = `${dest}.hypen-tmp-${process.pid}`;
  rmSync(staging, { recursive: true, force: true });
  try {
    cpSync(src, staging, { recursive: true });
    writeFileSync(join(staging, PROVISIONED_MARKER), PROVISIONED_NOTE);
    rmSync(dest, { recursive: true, force: true });
    renameSync(staging, dest);
  } finally {
    rmSync(staging, { recursive: true, force: true });
  }
}

/**
 * Provision the CLI's WIT for `abi` into `<crate>/wit` so the conventional
 * `wit_bindgen::generate!({ world: "module", path: "wit" })` resolves.
 *
 *  - absent → copy it (and drop the provisioning marker);
 *  - CLI-provisioned (marker, or — for crates provisioned before the marker
 *    existed — byte-identical to a bundled tree) but different from the WIT
 *    for `abi` → replace it, so an ABI switch or a CLI upgrade never builds
 *    against stale WIT;
 *  - author-vendored → left untouched, but a vendored WIT whose
 *    `hypen:module` version contradicts `abi` is a `BuildError` (it would
 *    otherwise silently build the wrong ABI).
 */
export function provisionRustWit(
  crateDir: string,
  abi: Abi,
  bundled: BundledWit = { "0.1": bundledModuleWit("0.1"), "0.2": bundledModuleWit("0.2") }
): WitProvisioning {
  const src = bundled[abi];
  const dest = join(crateDir, "wit");
  if (!existsSync(dest)) {
    installWit(src, dest);
    return "provisioned";
  }
  const marked = existsSync(join(dest, PROVISIONED_MARKER));
  if (marked || sameTree(dest, bundled["0.1"]) || sameTree(dest, bundled["0.2"])) {
    if (sameTree(dest, src)) {
      if (!marked) writeFileSync(join(dest, PROVISIONED_MARKER), PROVISIONED_NOTE);
      return "unchanged";
    }
    installWit(src, dest);
    return "refreshed";
  }
  const vendored = join(dest, MODULE_WIT_FILE);
  if (existsSync(vendored)) {
    const declared = readFileSync(vendored, "utf8").match(/hypen:module@(\d+\.\d+)/)?.[1];
    if (declared !== undefined && declared !== abi) {
      throw new BuildError(
        `${vendored} declares hypen:module@${declared} but the crate targets ABI ${abi} ` +
          `(Cargo.toml [package.metadata.hypen] abi).`,
        {
          code: "WIT_MISMATCH",
          file: vendored,
          hint: `update the vendored WIT to hypen:module@${abi}, or delete ${dest} to let the CLI provision it`,
        }
      );
    }
  }
  return "vendored";
}

/**
 * Whether an author-owned `wit/` plausibly holds the `hypen:module` package.
 * A `wit/` that does not (left over from another tool, or another project's
 * WIT) makes `wit_bindgen::generate!({ world: "module" })` fail with an error
 * that never mentions this directory, so the build points at it up front.
 */
export function vendoredWitDeclaresModule(crateDir: string): boolean {
  const dir = join(crateDir, "wit");
  let names: string[];
  try {
    names = readdirSync(dir);
  } catch {
    return false;
  }
  return names
    .filter((n) => n.endsWith(".wit"))
    .some((n) => /^\s*package\s+hypen:module@/m.test(readFileSync(join(dir, n), "utf8")));
}
